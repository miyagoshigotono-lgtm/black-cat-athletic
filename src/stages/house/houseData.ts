/** 床から立ち上がる箱（厚み = 上面の高さ） */
function block(name: string, x: number, z: number, w: number, d: number, top: number, color: BoxColor): BoxDef {
  return { name, x, z, w, d, top, h: top, color };
}

/** 厚み h の板・棚・天板 */
function slab(
  name: string, x: number, z: number, w: number, d: number, top: number, h: number,
  color: BoxColor, attachedTo?: string[],
): BoxDef {
  return { name, x, z, w, d, top, h, color, ...(attachedTo ? { attachedTo } : {}) };
}

/** 脚のある家具（天板＋4本脚）。天板の下は猫がくぐれる */
function legged(
  name: string, x: number, z: number, w: number, d: number, top: number, thickness: number, color: BoxColor,
): void {
  const legTop = top - thickness;
  const lx = w / 2 - 0.1;
  const lz = d / 2 - 0.1;
  const legs: string[] = [];
  for (const [i, [ox, oz]] of ([[-lx, -lz], [lx, -lz], [-lx, lz], [lx, lz]] as const).entries()) {
    const n = `${name}の脚${i + 1}`;
    boxes.push(slab(n, x + ox, z + oz, 0.1, 0.1, legTop, legTop, color));
    legs.push(n);
  }
  boxes.push(slab(`${name}の天板`, x, z, w, d, top, thickness, color, legs));
}

/** 円柱（鉢・支柱など） */
