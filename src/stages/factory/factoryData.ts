/** 床から立ち上がる箱（厚み = 上面の高さ） */
function block(name: string, x: number, z: number, w: number, d: number, top: number, color: BoxColor): BoxDef {
  return { name, x, z, w, d, top, h: top, color };
}

/** 厚み h の板・台（棚・ダクト・床など） */
function slab(
  name: string, x: number, z: number, w: number, d: number, top: number, h: number,
  color: BoxColor, attachedTo?: string[],
): BoxDef {
  return { name, x, z, w, d, top, h, color, ...(attachedTo ? { attachedTo } : {}) };
}

/** 縦の円柱（ドラム缶・配管・柱） */
function pipe(name: string, x: number, z: number, r: number, bottom: number, top: number, color: BoxColor): void {
  solids.push({ kind: 'cylinder', name, x, z, r, bottom, top, color });
}

/** 登れる面（金網・はしご・ネット・立てかけたパレット）。入れ物の面に埋め込む */
function climbable(name: string, look: 'mesh' | 'vine', into: string, o: {
  x: number; z: number; w: number; d: number; top: number; h: number;
}): void {
  climbables.push({ kind: 'climbable', name, look, embeddedIn: into, ...o });
}

