/**
 * ① 最小プロトタイプ用の検証コース（グレーボックス・使い捨て前提）。
 *
 * 座標系：単位はメートル、Y が上。地面の上面を y = 0 とする。
 * 開始地点は原点 (0, 0, 0)。カメラ初期向きでは -Z が「前」。
 *
 * 箱は「上面の高さ top」と「厚み h」で指定する。底面 = top - h、中心 y = top - h / 2。
 * これにより「地面高さと原点のズレ」「宙に浮く箱」を防ぐ。
 * 検算は scripts/verify-course.ts（npm run verify:course）で行う。
 *
 * このファイルは他のモジュールに依存しない（Node から直接検算できるようにするため）。
 */

export type BoxColor = 'ground' | 'wall' | 'step' | 'platform' | 'fence' | 'furniture' | 'tunnel';

export interface BoxDef {
  /** 識別名（検算ログ用） */
  name: string;
  /** 中心の X */
  x: number;
  /** 中心の Z */
  z: number;
  /** X 方向の幅 */
  w: number;
  /** Z 方向の奥行き */
  d: number;
  /** 上面の高さ */
  top: number;
  /** 厚み（Y 方向） */
  h: number;
  color: BoxColor;
  /** 地面そのもの（支持判定の対象外） */
  isGround?: boolean;
}

/** 猫カプセルの寸法（CatParams と一致させること） */
export const CAT_RADIUS = 0.12;
export const CAT_HALF_HEIGHT = 0.08;

/** 開始地点（猫の足元の位置） */
export const START_POSITION = { x: 0, y: 0, z: 0 } as const;

/** 地面から立ち上がる箱（厚み = 上面高さ）を作る補助 */
function block(name: string, x: number, z: number, w: number, d: number, top: number, color: BoxColor): BoxDef {
  return { name, x, z, w, d, top, h: top, color };
}

const boxes: BoxDef[] = [];

// ---------------------------------------------------------------
// 地面と外周の壁（30m × 30m、x・z とも -15〜15）
// ---------------------------------------------------------------
boxes.push({ name: '地面', x: 0, z: 0, w: 30, d: 30, top: 0, h: 0.5, color: 'ground', isGround: true });
boxes.push(block('外周壁・北', 0, -14.75, 30, 0.5, 2, 'wall'));
boxes.push(block('外周壁・南', 0, 14.75, 30, 0.5, 2, 'wall'));
boxes.push(block('外周壁・西', -14.75, 0, 0.5, 29, 2, 'wall'));
boxes.push(block('外周壁・東', 14.75, 0, 0.5, 29, 2, 'wall'));

// ---------------------------------------------------------------
// A. 段差（z = -4 の列）：自動乗り上げ 0.1m 以下 / ジャンプが必要な段
// ---------------------------------------------------------------
boxes.push(block('段差0.1', -4.5, -4, 1, 1, 0.1, 'step'));
boxes.push(block('段差0.2', -3.0, -4, 1, 1, 0.2, 'step'));
boxes.push(block('段差0.5', -1.5, -4, 1, 1, 0.5, 'step'));
boxes.push(block('段差1.0', 0.0, -4, 1, 1, 1.0, 'step'));

// 0.1m 刻みの階段（x = 3、手前から奥 -Z へ上る。各段の奥行き 0.4）
// z 範囲：-3.0〜-3.4, -3.4〜-3.8, … と隙間なく並ぶ
for (let i = 0; i < 5; i++) {
  const top = Number((0.1 * (i + 1)).toFixed(2));
  const z = Number((-3.2 - 0.4 * i).toFixed(2));
  boxes.push(block(`階段${i + 1}段目`, 3, z, 1, 0.4, top, 'step'));
}

// ---------------------------------------------------------------
// B. 高台（z = -8 の列、x 方向に 1.2m 四方の柱を隙間なく並べる）
//    上面 0.8 → 1.4 → 2.0 → 2.5 → 3.0。各段差 0.8m 以下なのでジャンプで登れる。
//    2m・3m からの落下確認用。
// ---------------------------------------------------------------
const towerTops = [0.8, 1.4, 2.0, 2.5, 3.0];
towerTops.forEach((top, i) => {
  const x = Number((4.6 + 1.2 * i).toFixed(2));
  boxes.push(block(`高台${top}m`, x, -8, 1.2, 1.2, top, 'platform'));
});

// ---------------------------------------------------------------
// C. 飛び移り（上面 1.0m の足場、隙間 1.0m と 1.8m）
//    足場1：x -8.75〜-7.25 / 足場2：x -6.25〜-4.75 / 足場3：x -2.95〜-1.45
//    足場1の手前（+Z 側）に上面 0.5m の踏み台。
// ---------------------------------------------------------------
boxes.push(block('飛び移り踏み台', -8, -8.75, 1, 1, 0.5, 'step'));
boxes.push(block('飛び移り足場1', -8, -10, 1.5, 1.5, 1.0, 'platform'));
boxes.push(block('飛び移り足場2', -5.5, -10, 1.5, 1.5, 1.0, 'platform'));
boxes.push(block('飛び移り足場3', -2.2, -10, 1.5, 1.5, 1.0, 'platform'));

// ---------------------------------------------------------------
// D. 狭い隙間（z = 4 の塀、厚み 0.2、高さ 1.5）
//    隙間 0.30m（猫の直径 0.24 より広い → 通れる）
//    隙間 0.20m（猫の直径より狭い → 通れない）
// ---------------------------------------------------------------
boxes.push(block('隙間塀1', -10.575, 4, 2.85, 0.2, 1.5, 'fence')); // x -12.00〜-9.15
boxes.push(block('隙間塀2', -6.975, 4, 3.75, 0.2, 1.5, 'fence')); // x -8.85〜-5.10
boxes.push(block('隙間塀3', -3.45, 4, 2.9, 0.2, 1.5, 'fence')); // x -4.90〜-2.00

// ---------------------------------------------------------------
// E. 天井の低いトンネル（x = 4、z 2〜6、内寸 幅0.6 × 高さ0.5）
// ---------------------------------------------------------------
boxes.push(block('トンネル左壁', 3.6, 4, 0.2, 4, 0.5, 'tunnel')); // x 3.5〜3.7
boxes.push(block('トンネル右壁', 4.4, 4, 0.2, 4, 0.5, 'tunnel')); // x 4.3〜4.5
boxes.push({ name: 'トンネル天井', x: 4, z: 4, w: 1, d: 4, top: 0.7, h: 0.2, color: 'tunnel' }); // 底面0.5 = 壁の上面

// ---------------------------------------------------------------
// F. 高い壁の狭い通路（カメラめり込み検証用、幅 0.8、壁高 2.5、L字）
//    縦通路：x 7.6〜8.4、z 2.0〜7.2 → 曲がって横通路：z 7.2〜8.0、x 8.4〜11.0
// ---------------------------------------------------------------
boxes.push(block('通路西壁', 7.5, 5.1, 0.2, 6.2, 2.5, 'wall')); // x 7.4〜7.6、z 2.0〜8.2
boxes.push(block('通路東壁', 8.5, 4.6, 0.2, 5.2, 2.5, 'wall')); // x 8.4〜8.6、z 2.0〜7.2
boxes.push(block('通路北壁', 9.3, 8.1, 3.4, 0.2, 2.5, 'wall')); // x 7.6〜11.0、z 8.0〜8.2
boxes.push(block('通路南壁', 9.8, 7.1, 2.4, 0.2, 2.5, 'wall')); // x 8.6〜11.0、z 7.0〜7.2

// ---------------------------------------------------------------
// G. 机（人間の実寸：天板上面 0.72m、脚の下をくぐれる）
//    天板：x -3.6〜-2.4、z 1.1〜1.9、厚み 0.04（底面 0.68）
//    脚：5cm 角、高さ 0.68、天板の四隅から 2.5cm 内側
// ---------------------------------------------------------------
boxes.push({ name: '机・天板', x: -3, z: 1.5, w: 1.2, d: 0.8, top: 0.72, h: 0.04, color: 'furniture' });
for (const lx of [-3.575, -2.425]) {
  for (const lz of [1.125, 1.875]) {
    boxes.push(block(`机・脚(${lx},${lz})`, lx, lz, 0.05, 0.05, 0.68, 'furniture'));
  }
}

export const PROTO_COURSE: readonly BoxDef[] = boxes;
